import uuid
from datetime import datetime, timezone
from sqlalchemy import Column, String, Text, Float, Integer, Boolean, DateTime, ForeignKey, JSON
from sqlalchemy.orm import relationship
from app.core.database import Base


class InterventionStrategy(str):
    PREREQUISITE_LESSON = "prerequisite_lesson"
    WORKED_EXAMPLE = "worked_example"
    GUIDED_PRACTICE = "guided_practice"
    INDEPENDENT_PRACTICE = "independent_practice"
    INTERACTIVE_VISUALIZATION = "interactive_visualization"
    CONCEPTUAL_EXPLANATION = "conceptual_explanation"
    SOCRATIC_TUTORING = "socratic_tutoring"
    PRACTICE_QUIZ = "practice_quiz"
    TEACHER_LED_REVIEW = "teacher_led_review"


class InterventionStatus(str):
    PROPOSED = "proposed"
    APPROVED = "approved"
    MODIFIED = "modified"
    REJECTED = "rejected"
    IN_PROGRESS = "in_progress"
    COMPLETED = "completed"


class TeacherReviewStatus(str):
    PENDING_REVIEW = "pending_review"
    APPROVED = "approved"
    REJECTED = "rejected"
    MODIFIED = "modified"
    MORE_EVIDENCE_REQUESTED = "more_evidence_requested"


class Intervention(Base):
    """
    Main intervention container tracking the learning remediation cycle.
    """
    __tablename__ = "interventions"

    id = Column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    student_id = Column(String(36), ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True)
    target_concept = Column(String(255), nullable=False)
    target_topic_id = Column(String(36), ForeignKey("topics.id", ondelete="SET NULL"), nullable=True, index=True)
    selected_strategy = Column(String(100), nullable=False, default=InterventionStrategy.WORKED_EXAMPLE)
    
    # Rationale and explainability
    reason = Column(Text, nullable=False)
    confidence = Column(Float, default=0.85)
    expected_goal = Column(String(255), nullable=True)
    
    # Governance and state
    status = Column(String(50), default=InterventionStatus.PROPOSED, nullable=False)
    teacher_status = Column(String(50), default=TeacherReviewStatus.PENDING_REVIEW, nullable=False)
    current_version_num = Column(Integer, default=1)
    
    # Associated assessment that triggered it
    trigger_assessment_id = Column(String(36), ForeignKey("assessments.id", ondelete="SET NULL"), nullable=True)
    reassessment_id = Column(String(36), ForeignKey("assessments.id", ondelete="SET NULL"), nullable=True)
    
    created_at = Column(DateTime(timezone=True), default=lambda: datetime.now(timezone.utc), nullable=False)
    approved_at = Column(DateTime(timezone=True), nullable=True)
    completed_at = Column(DateTime(timezone=True), nullable=True)

    # Relationships
    student = relationship("User", back_populates="interventions")
    target_topic = relationship("Topic")
    candidates = relationship("InterventionCandidate", back_populates="intervention", cascade="all, delete-orphan")
    versions = relationship("InterventionVersion", back_populates="intervention", cascade="all, delete-orphan", order_by="InterventionVersion.version_num")
    outcome = relationship("InterventionOutcome", back_populates="intervention", uselist=False, cascade="all, delete-orphan")


class InterventionCandidate(Base):
    """
    Candidate learning options generated by Agent 4 (Intervention Simulator)
    ranked with explainable scoring formulas.
    """
    __tablename__ = "intervention_candidates"

    id = Column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    intervention_id = Column(String(36), ForeignKey("interventions.id", ondelete="CASCADE"), nullable=False, index=True)
    strategy = Column(String(100), nullable=False)
    title = Column(String(255), nullable=False)
    intended_objective = Column(String(255), nullable=False)
    reason = Column(Text, nullable=False)
    supporting_evidence = Column(JSON, nullable=True)  # list of question errors, mastery states
    estimated_effort_minutes = Column(Integer, default=15)
    difficulty = Column(String(50), default="intermediate")
    expected_benefit_score = Column(Float, default=0.8)  # 0.0 to 1.0
    uncertainty = Column(Float, default=0.15)  # 0.0 to 1.0
    ranking_score = Column(Float, default=0.0)  # Calculated explainable score
    is_recommended = Column(Boolean, default=False)
    content_preview = Column(Text, nullable=True)

    # Relationships
    intervention = relationship("Intervention", back_populates="candidates")


class InterventionVersion(Base):
    """
    Versioned record of the intervention content (preserves original AI recommendation
    vs teacher-modified revisions).
    """
    __tablename__ = "intervention_versions"

    id = Column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    intervention_id = Column(String(36), ForeignKey("interventions.id", ondelete="CASCADE"), nullable=False, index=True)
    version_num = Column(Integer, nullable=False, default=1)
    title = Column(String(255), nullable=False)
    strategy = Column(String(100), nullable=False)
    content = Column(JSON, nullable=False)  # {"steps": [...], "markdown": "...", "exercises": [...]}
    created_by_role = Column(String(50), default="ai")  # 'ai' or 'teacher'
    author_id = Column(String(36), nullable=True)
    change_notes = Column(Text, nullable=True)
    is_active = Column(Boolean, default=True)
    created_at = Column(DateTime(timezone=True), default=lambda: datetime.now(timezone.utc), nullable=False)

    # Relationships
    intervention = relationship("Intervention", back_populates="versions")


class InterventionOutcome(Base):
    """
    Measured results by Agent 6 (Outcome Agent) following intervention completion
    and reassessment.
    """
    __tablename__ = "intervention_outcomes"

    id = Column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    intervention_id = Column(String(36), ForeignKey("interventions.id", ondelete="CASCADE"), unique=True, nullable=False)
    student_id = Column(String(36), ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True)
    
    baseline_score = Column(Float, nullable=False)  # pre-intervention assessment score %
    post_score = Column(Float, nullable=False)  # post-intervention reassessment score %
    score_difference = Column(Float, nullable=False)  # post - pre
    
    success = Column(Boolean, default=True)
    objective_met = Column(Boolean, default=True)
    
    topic_mastery_before = Column(JSON, nullable=True)  # {"recursion": 42.0}
    topic_mastery_after = Column(JSON, nullable=True)   # {"recursion": 78.0}
    remaining_misconceptions = Column(JSON, nullable=True)
    next_recommendation = Column(Text, nullable=True)
    
    measured_at = Column(DateTime(timezone=True), default=lambda: datetime.now(timezone.utc), nullable=False)

    # Relationships
    intervention = relationship("Intervention", back_populates="outcome")
